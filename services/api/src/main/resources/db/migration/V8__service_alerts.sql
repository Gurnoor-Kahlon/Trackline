-- Service alerts, with a lifecycle Trackline observes rather than reads.
--
-- The TTC's alerts feed publishes no active period: nothing says when an alert
-- starts or ends, and the field is deprecated in the specification itself. The only
-- honest lifecycle is the one Trackline sees. So each row is one continuous
-- stretch of an alert being present in the feed:
--
--   first_seen_at   the first cycle that contained it
--   last_seen_at    the latest cycle that contained it
--   resolved_at     the first cycle that did not, or null while it is still there
--
-- resolved_at is therefore an upper bound on when the alert ended, never the moment
-- it did, and first_seen_at is an upper bound on when it began.
--
-- source_alert_id is the publisher's identifier. It is not the primary key because
-- an alert can disappear and later come back under the same id, and that is a new
-- stretch with its own start, not an extension of the old one. Only one stretch per
-- source id can be open at a time, which the partial unique index enforces.

CREATE TABLE service_alerts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_alert_id TEXT        NOT NULL,
    -- GTFS-Realtime Cause and Effect enum numbers, as published. The TTC currently
    -- publishes UNKNOWN_CAUSE (1) and UNKNOWN_EFFECT (8) on every alert; that is
    -- stored as it arrives and not interpreted.
    cause           SMALLINT,
    effect          SMALLINT,
    -- The publisher's header is cut off at about 31 characters, mid-word, so the
    -- description is the complete text. Both are stored as published.
    header          TEXT,
    description     TEXT,
    url             TEXT,
    -- SHA-256 over everything above and the affected entities, so a cycle can tell
    -- "unchanged" from "edited" without comparing field by field.
    content_hash    TEXT        NOT NULL,
    first_seen_at   TIMESTAMPTZ NOT NULL,
    last_seen_at    TIMESTAMPTZ NOT NULL,
    -- When the content last differed from what was stored; equals first_seen_at
    -- until the publisher edits the alert.
    last_changed_at TIMESTAMPTZ NOT NULL,
    resolved_at     TIMESTAMPTZ,
    CONSTRAINT service_alerts_hash_check CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT service_alerts_seen_order_check CHECK (last_seen_at >= first_seen_at),
    CONSTRAINT service_alerts_changed_order_check CHECK (last_changed_at >= first_seen_at),
    CONSTRAINT service_alerts_resolved_order_check CHECK (resolved_at IS NULL OR resolved_at >= last_seen_at)
);

-- At most one open stretch per publisher id; this is also the lookup the cycle uses.
CREATE UNIQUE INDEX service_alerts_open_source_idx
    ON service_alerts (source_alert_id) WHERE resolved_at IS NULL;

-- The list endpoint: newest first, within active or resolved.
CREATE INDEX service_alerts_first_seen_idx ON service_alerts (first_seen_at DESC);

-- What an alert is about. Route and stop ids are stored exactly as published and are
-- deliberately not foreign keys: alerts arrive independently of schedule imports, and
-- an id the schedule does not know must be kept and reported, not rejected. Reads
-- join to routes and stops and say which ids did not resolve.
CREATE TABLE service_alert_entities (
    alert_id BIGINT NOT NULL REFERENCES service_alerts (id) ON DELETE CASCADE,
    route_id TEXT,
    stop_id  TEXT,
    CONSTRAINT service_alert_entities_named_check CHECK (route_id IS NOT NULL OR stop_id IS NOT NULL)
);

-- The feed repeats an entity within one alert, so a pair is stored once.
CREATE UNIQUE INDEX service_alert_entities_unique_idx
    ON service_alert_entities (alert_id, COALESCE(route_id, ''), COALESCE(stop_id, ''));
CREATE INDEX service_alert_entities_route_idx ON service_alert_entities (route_id) WHERE route_id IS NOT NULL;
CREATE INDEX service_alert_entities_stop_idx ON service_alert_entities (stop_id) WHERE stop_id IS NOT NULL;
