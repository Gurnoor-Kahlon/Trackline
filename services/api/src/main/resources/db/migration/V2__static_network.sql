-- The static TTC network, imported wholesale from the GTFS feed.
--
-- One active network is held at a time: a GTFS id is the natural primary key and
-- feed_version_id records which import wrote the row. An import runs in a single
-- transaction and only flips its version to ACTIVE at the end, so a failed
-- import can never leave a half-loaded network behind.

CREATE TABLE gtfs_feed_versions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- varchar, not char: Postgres blank-pads char and comparisons then depend on
    -- padding. The format check is stronger than a fixed length anyway.
    sha256          VARCHAR(64) NOT NULL,
    source_url      TEXT        NOT NULL,
    downloaded_at   TIMESTAMPTZ NOT NULL,
    imported_at     TIMESTAMPTZ,
    -- The published feed can describe a future service period, so the window is
    -- recorded and schedule-derived features check it instead of assuming the
    -- feed covers today.
    feed_start_date DATE,
    feed_end_date   DATE,
    row_counts      JSONB,
    status          TEXT        NOT NULL,
    CONSTRAINT gtfs_feed_versions_sha256_key UNIQUE (sha256),
    CONSTRAINT gtfs_feed_versions_sha256_format_check CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT gtfs_feed_versions_status_check
        CHECK (status IN ('IMPORTING', 'ACTIVE', 'FAILED', 'SUPERSEDED')),
    CONSTRAINT gtfs_feed_versions_dates_check
        CHECK (feed_end_date IS NULL OR feed_start_date IS NULL OR feed_end_date >= feed_start_date)
);

-- At most one version may be ACTIVE. Enforced by the database rather than by
-- import code, because "which network is live" must never be ambiguous.
CREATE UNIQUE INDEX gtfs_feed_versions_one_active_idx
    ON gtfs_feed_versions (status)
    WHERE status = 'ACTIVE';

COMMENT ON TABLE gtfs_feed_versions IS
    'One row per GTFS static import; sha256 makes re-importing an unchanged feed a no-op.';


CREATE TABLE routes (
    route_id          TEXT     NOT NULL PRIMARY KEY,
    feed_version_id   BIGINT   NOT NULL REFERENCES gtfs_feed_versions (id),
    short_name        TEXT     NOT NULL,
    long_name         TEXT     NOT NULL,
    route_type        SMALLINT NOT NULL,
    color             VARCHAR(6),
    text_color        VARCHAR(6),
    -- Derived, not from the feed: the TTC publishes no subway realtime, so
    -- route_type 1 has schedule and alerts but never live vehicles.
    supports_realtime BOOLEAN  NOT NULL,
    CONSTRAINT routes_route_type_check CHECK (route_type BETWEEN 0 AND 12),
    CONSTRAINT routes_color_format_check CHECK (color IS NULL OR color ~ '^[0-9A-Fa-f]{6}$'),
    CONSTRAINT routes_text_color_format_check
        CHECK (text_color IS NULL OR text_color ~ '^[0-9A-Fa-f]{6}$')
);

CREATE INDEX routes_short_name_idx ON routes (short_name);
CREATE INDEX routes_feed_version_idx ON routes (feed_version_id);

-- Route search matches number and name together ("501", "Queen", "501 Queen").
CREATE INDEX routes_search_trgm_idx
    ON routes USING gin ((short_name || ' ' || long_name) gin_trgm_ops);


-- Derived, because the TTC feed supplies no station hierarchy at all:
-- location_type and parent_station are empty for every one of its 9,409 stops.
-- Stations are clustered from stop names and positions, and derivation_method
-- records how, so the UI can present them as grouped stops rather than implying
-- the feed provided them.
CREATE TABLE stations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              TEXT                   NOT NULL,
    centroid          geography(Point, 4326) NOT NULL,
    stop_count        INTEGER                NOT NULL,
    derivation_method TEXT                   NOT NULL,
    CONSTRAINT stations_stop_count_check CHECK (stop_count > 0)
);

CREATE INDEX stations_centroid_gix ON stations USING gist (centroid);
CREATE INDEX stations_name_trgm_idx ON stations USING gin (name gin_trgm_ops);


CREATE TABLE stops (
    stop_id             TEXT                   NOT NULL PRIMARY KEY,
    feed_version_id     BIGINT                 NOT NULL REFERENCES gtfs_feed_versions (id),
    code                TEXT,
    name                TEXT                   NOT NULL,
    location            geography(Point, 4326) NOT NULL,
    -- GTFS values: 0 unknown, 1 accessible, 2 not accessible. Stored as given;
    -- absent accessibility information is never inferred.
    wheelchair_boarding SMALLINT               NOT NULL DEFAULT 0,
    station_id          BIGINT                 REFERENCES stations (id) ON DELETE SET NULL,
    CONSTRAINT stops_wheelchair_boarding_check CHECK (wheelchair_boarding BETWEEN 0 AND 2)
);

-- Drives nearest-stop and nearby-transit queries (ST_DWithin / ST_Distance).
CREATE INDEX stops_location_gix ON stops USING gist (location);
CREATE INDEX stops_name_trgm_idx ON stops USING gin (name gin_trgm_ops);
CREATE INDEX stops_station_idx ON stops (station_id);
CREATE INDEX stops_feed_version_idx ON stops (feed_version_id);


CREATE TABLE calendar_services (
    service_id      TEXT    NOT NULL PRIMARY KEY,
    feed_version_id BIGINT  NOT NULL REFERENCES gtfs_feed_versions (id),
    monday          BOOLEAN NOT NULL,
    tuesday         BOOLEAN NOT NULL,
    wednesday       BOOLEAN NOT NULL,
    thursday        BOOLEAN NOT NULL,
    friday          BOOLEAN NOT NULL,
    saturday        BOOLEAN NOT NULL,
    sunday          BOOLEAN NOT NULL,
    start_date      DATE    NOT NULL,
    end_date        DATE    NOT NULL,
    CONSTRAINT calendar_services_dates_check CHECK (end_date >= start_date)
);

CREATE TABLE calendar_exceptions (
    service_id     TEXT     NOT NULL REFERENCES calendar_services (service_id) ON DELETE CASCADE,
    exception_date DATE     NOT NULL,
    -- GTFS exception_type: 1 service added, 2 service removed.
    exception_type SMALLINT NOT NULL,
    PRIMARY KEY (service_id, exception_date),
    CONSTRAINT calendar_exceptions_type_check CHECK (exception_type IN (1, 2))
);


CREATE TABLE trips (
    trip_id         TEXT     NOT NULL PRIMARY KEY,
    feed_version_id BIGINT   NOT NULL REFERENCES gtfs_feed_versions (id),
    route_id        TEXT     NOT NULL REFERENCES routes (route_id),
    service_id      TEXT     NOT NULL REFERENCES calendar_services (service_id),
    direction_id    SMALLINT NOT NULL,
    headsign        TEXT,
    shape_id        TEXT,
    block_id        TEXT,
    CONSTRAINT trips_direction_id_check CHECK (direction_id IN (0, 1))
);

CREATE INDEX trips_route_direction_service_idx ON trips (route_id, direction_id, service_id);
CREATE INDEX trips_shape_idx ON trips (shape_id);

COMMENT ON TABLE trips IS
    'Scheduled trips. Realtime trip_id does not join to this table (measured 2 of 1050 matching), so realtime data is keyed on route_id and geometry instead.';


CREATE TABLE stop_times (
    trip_id             TEXT    NOT NULL REFERENCES trips (trip_id) ON DELETE CASCADE,
    stop_sequence       INTEGER NOT NULL,
    stop_id             TEXT    NOT NULL REFERENCES stops (stop_id),
    -- Seconds after midnight, because GTFS times legitimately exceed 24:00:00
    -- for trips running past midnight.
    arrival_seconds     INTEGER NOT NULL,
    departure_seconds   INTEGER NOT NULL,
    shape_dist_traveled NUMERIC(12, 4),
    PRIMARY KEY (trip_id, stop_sequence),
    CONSTRAINT stop_times_arrival_check CHECK (arrival_seconds >= 0),
    CONSTRAINT stop_times_departure_check CHECK (departure_seconds >= arrival_seconds)
);

-- Scheduled arrivals for a stop, in time order.
CREATE INDEX stop_times_stop_arrival_idx ON stop_times (stop_id, arrival_seconds);


-- Route geometry, aggregated from shapes.txt points.
--
-- Two representations on purpose: geom is metre-based (EPSG:3857) because
-- ST_LineLocatePoint and length maths need planar units, and geom_wgs is a
-- geography for display and true-distance checks.
CREATE TABLE route_shapes (
    shape_id        TEXT                        NOT NULL PRIMARY KEY,
    feed_version_id BIGINT                      NOT NULL REFERENCES gtfs_feed_versions (id),
    route_id        TEXT                        NOT NULL REFERENCES routes (route_id),
    direction_id    SMALLINT                    NOT NULL,
    geom            geometry(LineString, 3857)  NOT NULL,
    geom_wgs        geography(LineString, 4326) NOT NULL,
    length_m        NUMERIC(12, 2)              NOT NULL,
    trip_count      INTEGER                     NOT NULL,
    -- The shape vehicles are projected onto for this route and direction: the
    -- variant used by the most trips.
    is_primary      BOOLEAN                     NOT NULL DEFAULT FALSE,
    -- Endpoints meet, so vehicle spacing must be computed circularly.
    is_loop         BOOLEAN                     NOT NULL DEFAULT FALSE,
    CONSTRAINT route_shapes_direction_id_check CHECK (direction_id IN (0, 1)),
    CONSTRAINT route_shapes_length_check CHECK (length_m > 0),
    CONSTRAINT route_shapes_trip_count_check CHECK (trip_count > 0)
);

CREATE INDEX route_shapes_geom_gix ON route_shapes USING gist (geom);
CREATE INDEX route_shapes_geom_wgs_gix ON route_shapes USING gist (geom_wgs);
CREATE INDEX route_shapes_route_direction_idx ON route_shapes (route_id, direction_id);

-- Exactly one primary shape per route and direction; anything else would make
-- vehicle progress ambiguous.
CREATE UNIQUE INDEX route_shapes_one_primary_idx
    ON route_shapes (route_id, direction_id)
    WHERE is_primary;
