-- Observability for every realtime ingestion cycle.
--
-- This is the honest source for the project's performance figures and the record
-- that distinguishes "the network is quiet" from "ingestion is failing". Written
-- once per cycle per feed, including cycles that fail or change nothing.

CREATE TABLE ingestion_runs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed                  TEXT        NOT NULL,
    started_at            TIMESTAMPTZ NOT NULL,
    duration_ms           INTEGER     NOT NULL,
    status                TEXT        NOT NULL,
    entity_count          INTEGER     NOT NULL DEFAULT 0,
    -- Entities dropped by validation, with the cycle still succeeding. A high
    -- ratio marks the cycle SUSPECT rather than silently degrading the data.
    rejected_count        INTEGER     NOT NULL DEFAULT 0,
    -- The feed's own header timestamp: an unchanged value means the publisher has
    -- not produced new data, which is recorded as NO_CHANGE rather than
    -- reprocessed.
    feed_header_timestamp TIMESTAMPTZ,
    error_summary         TEXT,
    CONSTRAINT ingestion_runs_feed_check
        CHECK (feed IN ('VEHICLE_POSITIONS', 'TRIP_UPDATES', 'ALERTS')),
    CONSTRAINT ingestion_runs_status_check
        CHECK (status IN ('SUCCESS', 'NO_CHANGE', 'SUSPECT', 'FAILED')),
    CONSTRAINT ingestion_runs_duration_check CHECK (duration_ms >= 0),
    CONSTRAINT ingestion_runs_entity_count_check CHECK (entity_count >= 0),
    CONSTRAINT ingestion_runs_rejected_count_check CHECK (rejected_count >= 0)
);

-- Latest runs per feed: freshness checks and the ingestion status endpoint.
CREATE INDEX ingestion_runs_feed_started_idx ON ingestion_runs (feed, started_at DESC);
