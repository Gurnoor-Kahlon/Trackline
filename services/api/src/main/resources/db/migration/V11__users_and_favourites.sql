-- Accounts, the tokens that keep them signed in, and what each saves.
--
-- Everything in Trackline that reads transit data stays open to anyone; an account exists only so a person
-- can keep a list of routes and stops. So nothing here is referenced by anything else, and the tables are
-- small: one row per person, a handful of tokens each, and a row per saved route or stop.

CREATE TABLE users (
    id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Stored trimmed and in lower case, so one address is one account whatever case it was typed in. The check
    -- keeps that true for any writer, not only this application.
    email         TEXT        NOT NULL,
    -- A BCrypt hash, which carries its own salt and cost. The password itself is never stored or logged.
    password_hash TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT users_email_check CHECK (
        email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 254 AND position('@' IN email) > 1),
    CONSTRAINT users_password_hash_check CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$.{53}$')
);

CREATE UNIQUE INDEX users_email_idx ON users (email);

-- Refresh tokens, which last long enough to be worth stealing, so they are stored only as a hash: a copy of
-- this table cannot be used to sign in. A token is used once. Each use ends it and issues the next in the same
-- family, so a stolen token and its owner cannot both keep going: when one is presented after it has been
-- exchanged, the whole family is ended.
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Every token descended from one sign-in.
    family_id  UUID        NOT NULL,
    -- SHA-256 of the token. The token is 256 random bits, so a fast hash is enough: there is nothing to guess.
    token_hash TEXT        NOT NULL,
    issued_at  TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    -- When it was exchanged for the next one.
    rotated_at TIMESTAMPTZ,
    -- When it, and so its family, was ended outright: signing out, or reuse after rotation.
    revoked_at TIMESTAMPTZ,
    CONSTRAINT refresh_tokens_hash_check CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT refresh_tokens_expiry_check CHECK (expires_at > issued_at)
);

CREATE UNIQUE INDEX refresh_tokens_hash_idx ON refresh_tokens (token_hash);
-- Ending a family, and signing a user out everywhere, find tokens by these.
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);
-- Retention removes tokens by how long ago they expired.
CREATE INDEX refresh_tokens_expiry_idx ON refresh_tokens (expires_at);

-- Saved routes and stops. The ids are the schedule's own and are not foreign keys: a schedule import replaces
-- the routes and stops tables, and a person's list must survive it. A saved id the schedule no longer knows is
-- kept and reported as such, as for alerts.
CREATE TABLE favourite_routes (
    user_id    UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    route_id   TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, route_id)
);

CREATE TABLE favourite_stops (
    user_id    UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    stop_id    TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, stop_id)
);

COMMENT ON TABLE users IS 'Accounts. Passwords are stored only as BCrypt hashes.';
COMMENT ON TABLE refresh_tokens IS 'Refresh tokens, stored as SHA-256 hashes, rotated on every use.';
