-- Bunching, recorded as events rather than as a row per cycle.
--
-- A bunch is vehicles running in a pack while a gap opens elsewhere on the same route. It
-- lasts for as long as the vehicles stay together, which can be many minutes, so one row is
-- opened when it is first seen, updated while it persists, and resolved when it has been
-- absent for several consecutive analyses. Otherwise a single bunch would write hundreds of
-- rows an hour.
--
-- Every time is one Trackline observed, as for alerts: first_seen_at is an upper bound on when
-- the pack formed and resolved_at on when it broke up.
--
-- route_id has no foreign key. This is history, and it must survive a schedule import that
-- replaces the routes table.

CREATE TABLE bunching_events (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id           TEXT        NOT NULL,
    direction_id       SMALLINT    NOT NULL,
    -- The vehicles in the bunch as of the latest sighting, sorted. A bunch that picks up or
    -- loses a vehicle is still the same event, so this changes; peak_vehicles keeps the most.
    vehicle_ids        TEXT[]      NOT NULL,
    peak_vehicles      INTEGER     NOT NULL,
    -- Latest sighting: how far the bunch spans, what spacing it was measured against, and the
    -- largest gap elsewhere on the direction.
    span_m             REAL        NOT NULL,
    expected_gap_m     REAL        NOT NULL,
    service_gap_m      REAL        NOT NULL,
    -- Where the expected spacing came from: the timetable, or the vehicles' own average.
    basis              TEXT        NOT NULL,
    severity           TEXT        NOT NULL,
    peak_severity      TEXT        NOT NULL,
    -- How many analyses saw it, and how many in a row have not since. Resolution is two misses.
    sightings          INTEGER     NOT NULL DEFAULT 1,
    missed_cycles      SMALLINT    NOT NULL DEFAULT 0,
    first_seen_at      TIMESTAMPTZ NOT NULL,
    last_seen_at       TIMESTAMPTZ NOT NULL,
    resolved_at        TIMESTAMPTZ,
    CONSTRAINT bunching_events_direction_check CHECK (direction_id IN (0, 1)),
    CONSTRAINT bunching_events_basis_check CHECK (basis IN ('SCHEDULE', 'OBSERVED')),
    CONSTRAINT bunching_events_severity_check CHECK (severity IN ('MODERATE', 'SEVERE')),
    CONSTRAINT bunching_events_peak_severity_check CHECK (peak_severity IN ('MODERATE', 'SEVERE')),
    CONSTRAINT bunching_events_vehicles_check CHECK (cardinality(vehicle_ids) >= 2 AND peak_vehicles >= 2),
    CONSTRAINT bunching_events_seen_order_check CHECK (last_seen_at >= first_seen_at),
    CONSTRAINT bunching_events_resolved_order_check CHECK (resolved_at IS NULL OR resolved_at >= last_seen_at),
    CONSTRAINT bunching_events_counts_check CHECK (sightings >= 1 AND missed_cycles >= 0)
);

-- The open bunches, which every analysis reads to decide what is new.
CREATE INDEX bunching_events_open_idx ON bunching_events (route_id, direction_id) WHERE resolved_at IS NULL;

-- A route's history, newest first: the endpoint behind the route panel.
CREATE INDEX bunching_events_route_idx ON bunching_events (route_id, first_seen_at DESC);
